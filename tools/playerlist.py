"""Write PlayerList.lua: the names published releases hide, and nothing else.

    uv run tools/playerlist.py              # update PlayerList.lua from data/
    uv run tools/playerlist.py --dry-run    # show who would be added or removed

Run it before a release (the publish-release skill does). The list holds names
only: never reasons, messages or evidence, which quote other people's chat.

A player is listed only once their case is settled:
- you decided to ignore them (tools/decide.py, /rbust ignore, or Block in game);
- or the reviewer ignored them at least SETTLE_DAYS ago and you haven't reversed it.
Anyone you unignored afterwards is left off. In a release, listed players' chat
is hidden; nothing touches anyone's Blizzard ignore list, and each user can
show a listed player again with /rbust unignore.
"""

from __future__ import annotations

import argparse
import re
import sys
import time
from pathlib import Path

import review
from wowlua import LuaParser, lua_value

REPO = Path(__file__).resolve().parent.parent
OUTPUT = REPO / "PlayerList.lua"
SETTLE_DAYS = 7
# A WoW character name and realm: letters (any alphabet), no spaces, quotes or punctuation
# beyond the realm's own hyphen and apostrophe.
NAME_RE = re.compile(r"^[^\W\d_]{2,12}-[\w'\-]{2,40}$")


def settled_names(data: Path, now: int) -> dict[str, str]:
    """name -> why it's listed, across every game flavor in data/."""
    names = {}
    for fl in sorted(p for p in data.glob("*") if (p / "log").is_dir()):
        state = review.load_state(fl)
        pardoned = review.read_json(fl / "game.json", {}).get("pardoned", {})
        for name, v in state["ignored"].items():
            if pardoned.get(name, 0) >= v.get("time", 0):
                continue                                 # you reversed it
            decided = state["decided"].get(name, {})
            if decided.get("decision") == "ignore":
                names[name] = "your decision"
            elif now - v.get("time", now) >= SETTLE_DAYS * 86400:
                names[name] = f"reviewer, unreversed for {SETTLE_DAYS}+ days"
    return names


def render(names: list[str]) -> str:
    return (
        "-- Generated by tools/playerlist.py from settled review decisions. Names only.\n"
        "-- Published releases hide these players' public chat. Each user can show\n"
        "-- someone again with /rbust unignore Name-Realm.\n"
        "local _, ns = ...\n"
        f"ns.listedPlayers = {lua_value({n: True for n in names})}\n"
    )


def current_names() -> set[str]:
    if not OUTPUT.exists():
        return set()
    text = OUTPUT.read_text(encoding="utf-8")
    table = text[text.index("ns.listedPlayers"):].split("=", 1)[1]
    return set(LuaParser(table).value() or {})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--data", type=Path, default=REPO / "data", help="the repo's data folder")
    parser.add_argument("--dry-run", action="store_true", help="show the changes without writing")
    args = parser.parse_args()
    sys.stdout.reconfigure(errors="replace")

    found = settled_names(args.data, int(time.time()))
    bad = sorted(n for n in found if not NAME_RE.match(n))
    for n in bad:
        print(f"Skipping {n!r}: it doesn't look like a Name-Realm.", file=sys.stderr)
    names = sorted(n for n in found if n not in bad)

    before = current_names()
    added, removed = sorted(set(names) - before), sorted(before - set(names))
    for n in added:
        print(f"  + {n}  ({found[n]})")
    for n in removed:
        print(f"  - {n}")
    print(f"{len(names)} players listed ({len(added)} added, {len(removed)} removed).")
    if args.dry_run:
        print("Dry run: PlayerList.lua not written.")
        return 0
    OUTPUT.write_text(render(names), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
